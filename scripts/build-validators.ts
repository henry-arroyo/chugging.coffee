/**
 * Compiles schemas/*.schema.json into standalone validator functions.
 *
 * The browser bundle never compiles schemas at runtime, so the page's CSP can forbid
 * eval and new Function. `--check` exits non-zero when the committed output is stale.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const root = new URL('..', import.meta.url).pathname;
const schemaDir = join(root, 'schemas');
const outFile = join(root, 'src/core/contracts/generated/validators.js');

/** Exported validator name for each schema file that is a top-level contract. */
export const CONTRACTS = {
  'world-release': 'validateWorldRelease',
  'site-manifest': 'validateSiteManifest',
  'page-document': 'validatePageDocument',
  'widget-props': 'validateWidget',
  'asset-rights': 'validateAssetRegistry',
  profile: 'validateProfile',
  'window-geometry': 'validateWindowGeometry',
  'virtual-file': 'validateVirtualFile',
  'game-snapshot': 'validateGameSnapshot',
  'app-manifest': 'validateAppManifest',
  'host-events': 'validateHostEvent',
  'save-export': 'validateSaveExport',
} as const;

const ID_BASE = 'https://chugging.coffee/time-machine/schemas/';

export function createAjv() {
  const ajv = new Ajv2020({
    strict: true,
    // Conditional "then" branches name properties declared in the parent schema.
    strictRequired: false,
    allErrors: false,
    code: { source: true, esm: true },
  });
  for (const file of readdirSync(schemaDir).filter((f) => f.endsWith('.schema.json')).sort()) {
    ajv.addSchema(JSON.parse(readFileSync(join(schemaDir, file), 'utf8')));
  }
  return ajv;
}

/**
 * Ajv's ESM output still require()s two runtime helpers. Replace them with local
 * equivalents so the module is plain ESM with no dependency on ajv at runtime.
 */
const RUNTIME_HELPERS: Record<string, string> = {
  'ajv/dist/runtime/ucs2length': `function(str) {
  // Length in Unicode code points, as JSON Schema defines it.
  let length = 0;
  for (const _ of str) length++;
  return length;
}`,
  'ajv/dist/runtime/equal': `function equal(a, b) {
  // Structural equality for JSON values.
  if (a === b) return true;
  if (typeof a !== 'object' || typeof b !== 'object' || a === null || b === null) return false;
  if (Array.isArray(a) !== Array.isArray(b)) return false;
  if (Array.isArray(a)) {
    if (a.length !== b.length) return false;
    for (let i = 0; i < a.length; i++) if (!equal(a[i], b[i])) return false;
    return true;
  }
  const ka = Object.keys(a);
  if (ka.length !== Object.keys(b).length) return false;
  for (const k of ka) if (!Object.prototype.hasOwnProperty.call(b, k) || !equal(a[k], b[k])) return false;
  return true;
}`,
};

function inlineRuntimeHelpers(code: string): string {
  const out = code.replace(/const (\w+) = require\("([^"]+)"\)\.default;/g, (_m, name: string, mod: string) => {
    const helper = RUNTIME_HELPERS[mod];
    if (!helper) throw new Error(`Unexpected runtime helper in generated validators: ${mod}`);
    return `const ${name} = ${helper};`;
  });
  if (/\brequire\(/.test(out)) throw new Error('Generated validators still contain require()');
  return out;
}

export function buildValidatorsSource(): string {
  const ajv = createAjv();
  const mapping: Record<string, string> = {};
  for (const [name, exportName] of Object.entries(CONTRACTS)) {
    mapping[exportName] = `${ID_BASE}${name}.schema.json`;
  }
  const code = inlineRuntimeHelpers(standaloneCode(ajv, mapping));
  return `// GENERATED by scripts/build-validators.ts from schemas/. Do not edit.\n/* eslint-disable */\n${code}\n`;
}

export const GENERATED_FILE = outFile;

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const code = buildValidatorsSource();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(outFile, 'utf8');
    } catch {
      /* missing counts as stale */
    }
    if (current !== code) {
      console.error('Generated validators are stale. Run: npm run contracts:build');
      process.exit(1);
    }
    console.log('Generated validators are up to date.');
  } else {
    writeFileSync(outFile, code);
    console.log(`Wrote ${outFile}`);
  }
}
